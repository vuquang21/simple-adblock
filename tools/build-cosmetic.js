// Regenerates cosmetic-rules.js from an EasyList-format file.
// Usage: node tools/build-cosmetic.js easylist.txt
// The filtering is parseCosmetic() from shared.js, so the list and the importer in
// the dashboard always agree on what counts as a usable rule.
// shortcut: run by hand when the upstream list moves; there is no build step.
const fs = require("fs");
const path = require("path");

const src = fs.readFileSync(path.join(__dirname, "../shared.js"), "utf8");
const { parseCosmetic } = new Function(src + "; return { parseCosmetic };")();

const input = process.argv[2];
if (!input) {
  console.error("usage: node tools/build-cosmetic.js <easylist.txt>");
  process.exit(1);
}

const rules = parseCosmetic(fs.readFileSync(input, "utf8"));
fs.writeFileSync(
  path.join(__dirname, "../cosmetic-rules.js"),
  `// GENERATED by tools/build-cosmetic.js from EasyList — do not edit by hand.\n` +
    `// Generic ## rules that are plain CSS, shipped as a content script.\n` +
    `const GENERIC_COSMETIC = ${JSON.stringify(rules)};\n`
);
console.log(`wrote cosmetic-rules.js with ${rules.length} selectors`);
